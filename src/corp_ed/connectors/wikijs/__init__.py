"""Адаптер Wiki.js 2.x (своя установка): страницы всех локалей с зеркалом
прав по API-ключу с полным доступом.

Написан по GraphQL-схеме и коду сервера requarks/wiki v2.5.315
(`server/graph/schemas/*.graphql`, `server/core/auth.js`) и проверен на
стенде 2.5.316 в Docker (`tests/live/wikijs/README.md`); формы ответов —
в тестах (`tests/connectors/fake_wikijs.py`).

Ограничения прав (в сторону закрытости):

- REGEX-правило, которое нельзя посчитать так же, как JavaScript
  (rules.py, _translate), — страница достаётся только тем, кому она
  открыта при любом его исходе; гостевой доступ через такое правило не
  делает страницу общей.
- Неопубликованные страницы и страницы вне окна публикации не берутся
  (их видят только редакторы); `isPrivate` (личные страницы 2.x не
  используют) — тоже.
- Почты — только активных пользователей; гость и системные учётки не в
  списке.
- Правила групп на `read:pages` зеркалируются полностью; права на
  комментарии, историю и исходник ассистенту не нужны.

Размер: `pages.list` в Wiki.js 2 без постраничности — вся вики одним
ответом; ответ больше лимита OutboundClient (20 МБ, порядка десятков
тысяч страниц) останавливает обход с кодом `response_too_large`.
"""

