"""Короткий идентификатор компании для нашей команды.

Код компании (company_code) — транслитерация названия, а у клиента-ИП
название — это фамилия («ИП Иванов» → ip-ivanov), то есть персональные
данные. В уведомления команде (Telegram — иностранный сервис) и в
обезличенные записи идёт не код, а первые 8 символов UUID компании: по
ним команда находит компанию в нашей панели, а сами по себе они ничего
о клиенте не говорят.
"""

from uuid import UUID

REF_LENGTH = 8


def company_ref(tenant_id: UUID) -> str:
    return str(tenant_id)[:REF_LENGTH]
