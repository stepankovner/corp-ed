_NAME = re.compile(r"\b(?:ассистент|бот|помощник|коллега|коллеги|друг|алиса)\b")
_NOISE = re.compile(r"[\s!?.,;:()\-–—«»\"'…]+|[\U0001F300-\U0001FAFF☀-➿]+")


def _normalize(text: str) -> str:
    text = text.casefold().replace("ё", "е")
    text = _NOISE.sub(" ", text)
    return " ".join(text.split())


def _strip_name(text: str) -> str:
    return " ".join(_NAME.sub(" ", text).split())


def classify(message: str) -> Kind | None:
    """Вид реплики или None — это не реплика, решает модель.

    Совпадение — только целиком: «привет», «привет, ассистент!», «спасибо
    большое)))». «Привет! Какой лимит на такси?» — None.
    """
    text = _normalize(message)
    if not text or len(text) > 60:
        return None
    if _ABOUT.match(text) or _ABOUT.match(_strip_name(text)):
        return "about"
    bare = _strip_name(text)
    for kind, phrases in _PHRASES.items():
        if bare in phrases:
            return kind
    # Две реплики подряд: «привет спасибо», «спасибо пока».
    parts = bare.split()
    if 2 <= len(parts) <= 4:
        for cut in range(1, len(parts)):
            left, right = " ".join(parts[:cut]), " ".join(parts[cut:])
            kinds = (
                [k for k, ph in _PHRASES.items() if left in ph],
                [k for k, ph in _PHRASES.items() if right in ph],
            )
            if kinds[0] and kinds[1]:
                return kinds[1][0] if kinds[1][0] != "ack" else kinds[0][0]
    return None


def reply(kind: Kind) -> str:
    return _REPLIES[kind]


def rule_reply(message: str) -> str | None:
    """Готовый ответ на реплику или None."""
    kind = classify(message)
    return None if kind is None else reply(kind)
