"""Реплики без вопроса — ответ правилом, до модели и поиска.

Практика (обзор 20.10, ml-agent-plan.md §9): приветствия, благодарности
и вопрос об ассистенте обрабатывают до LLM — так у «Цифры» и в разборе
на Хабре 1094042; OpenAI: «не делайте всё через LLM». У нас шаг решения
на модели эти случаи путал («Кто ты?» — вопрос), а ответ через общий
промпт стоил вызова Flash.

Правило узкое и прозрачное: сообщение целиком — приветствие, благодарность,
прощание или короткое «ок» (можно с именем ассистента, эмодзи и знаками),
либо вопрос о самом ассистенте по списку оборотов. Любое сообщение, где
есть что-то ещё, — не реплика, его решает модель. Чистые функции.
"""

