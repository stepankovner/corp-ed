"""Порог отказа: «отвечать ли по документам» и «какие выдержки брать».

Один порог RAG_FAQ_MAX_DISTANCE делал обе работы: по ближайшему фрагменту
решал, есть ли ответ в документах, и им же отсекал выдержки для промпта.
Замер ML 04.10 (ml-report.md, «Порог: развести роли»): короткий вопрос
к табличному или списочному фрагменту («Как зовут главного бухгалтера?»)
бывает дальше 0,59, хотя нужный фрагмент — первый; поднять порог целиком
— в промпт добавляются дальние выдержки и портят ответы, которые
проходили и раньше. Поэтому роли разведены (BH-37):

- отвечать по документам, если ближайший фрагмент не дальше
  gate_distance;
- выдержки — до max_distance, как раньше; если ближайший дальше
  max_distance (но не дальше gate_distance) — он и выдержки не дальше
  него + near_margin.

Без gate_distance поведение прежнее. Функция чистая: расстояния — числа,
порядок выдачи не меняется.
"""


def relevance_limit(
    nearest: float | None,
    max_distance: float,
    gate_distance: float | None = None,
    near_margin: float = 0.0,
) -> float | None:
    """До какого косинусного расстояния выдержки идут в модель.

    None — ответа по документам нет (выдачи нет или ближайший фрагмент
    дальше порога).
    """
    if nearest is None:
        return None
    if nearest <= max_distance:
        return max_distance
    if gate_distance is not None and nearest <= gate_distance:
        return nearest + near_margin
    return None
