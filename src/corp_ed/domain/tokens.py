"""Оценка длины текста в токенах.

Все размеры в ML-части (нарезка, бюджет контекста) считаются в токенах,
а не в символах: у эмбеддера окно в токенах, и чанк, отмеренный
символами, молча обрезается при превышении — качество поиска падает
незаметно («Честный знак», чанки по 4096 символов в окне 512 токенов).

На pre-MVP точного токенизатора нет: у Яндекса он доступен только через
API, а ходить в сеть из нарезки нельзя. Поэтому приближение по замеру
на YandexGPT: кириллица — около трёх символов на токен. Округление
вверх даёт небольшой запас: оценка может ошибиться в сторону «длиннее»,
но не «короче», и чанк не вылезет за окно эмбеддера из-за округления.

Для модели эмбеддингов соотношение не проверено — его покажет
eval/probe_embedding_limit.py (поле numTokens в ответе API). Если оно
окажется другим, меняется одна константа ниже.
"""

import math

CHARS_PER_TOKEN = 3.0


def count_tokens(text: str) -> int:
    """Приближённое число токенов: ceil(len(text) / CHARS_PER_TOKEN)."""
    if not text:
        return 0
    return math.ceil(len(text) / CHARS_PER_TOKEN)
