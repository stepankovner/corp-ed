"""Заголовки, общие для всех запросов к Yandex AI Studio.

По умолчанию модели Яндекса сохраняют данные запросов для улучшения
сервиса (RISKS №48). Заголовок x-data-logging-enabled: false выключает
это для запроса — в выдержках из документов и вопросах сотрудников бывают
персональные и коммерческие данные (Р-3, ROADMAP.md).

Проверено на живом API 30.09: генерация (OpenAI-совместимый и нативный
API) и эмбеддинги отвечают 200 с заголовком; OpenAI-совместимый API
возвращает его в ответе, остальные — нет. Документация Яндекса называет
генерацию, классификаторы и YandexART; про эмбеддинги прямо не пишет —
заголовок передаём и туда.
"""

NO_DATA_LOGGING = {"x-data-logging-enabled": "false"}


def auth_headers(api_key: str) -> dict[str, str]:
    """Авторизация по API-ключу и запрет сохранять данные запроса."""
    return {"Authorization": f"Api-Key {api_key}", **NO_DATA_LOGGING}
