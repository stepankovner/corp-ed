def _replace_once(text: str, old: str, new: str) -> str:
    if text.count(old) != 1:
        raise RuntimeError(f"в промпте ответа нет ровно одного: {old[:40]}…")
    return text.replace(old, new)


_EDITION_SYSTEM_PROMPT = _replace_once(
    _replace_once(_SYSTEM_PROMPT, _RULE_4_OTHER, _RULE_4_EDITION),
    _EXAMPLE_OTHER,
    _EXAMPLE_EDITION,
)

_EDITION_REMINDER = (
    "Ответь по правилам: первой фразой — оговорка «В документах — …, а не ….» "
    "с годом, редакцией или датой из выдержек; дальше — ответ по выдержкам, "
    "после каждого утверждения — номер выдержки в квадратных скобках: [1], "
    "[2] (не номер пункта документа). Если нужного факта в этой редакции нет, "
    "после оговорки так и скажи и перескажи, что в выдержках есть по теме. "
    f"«{NOT_FOUND_ANSWER}» — только если в выдержках ничего нет по теме вопроса."
)


def _edition_facts(decision: Decision) -> str:
    """Что спросили и что нашли — из решения; без догадок, если поля пусты."""
    asked, present = quoted(decision.subject), quoted(decision.excerpts_subject)
    if asked and present and asked.casefold() != present.casefold():
        return (
            f"Вопрос — про {asked}, а выдержки — про {present}: это тот же "
            "документ или программа, но другой год, редакция или дата.\n\n"
        )
    if asked:
        return (
            f"Вопрос — про {asked}, а в выдержках — другой год, редакция или "
            "дата того же документа или программы.\n\n"
        )
    return (
        "В выдержках — другой год, редакция или дата того документа или "
        "программы, о которых вопрос.\n\n"
    )


def build_edition_messages(
    question: str, matches: Sequence[SourceChunk], decision: Decision
) -> list[Message]:
    """Ответ по выдержкам другой редакции (edition-v1): своя постановка
    задачи вместо подсказки хвостом к faq-v2.7."""
    return [
        Message(role=Role.SYSTEM, content=_EDITION_SYSTEM_PROMPT),
        Message(
            role=Role.USER,
            content=(
                "Выдержки из документов компании:\n\n"
                f"{format_excerpts(matches)}\n\n"
                f"Вопрос сотрудника: {question.strip()}\n\n"
                f"{_edition_facts(decision)}{_EDITION_REMINDER}"
            ),
        ),
    ]


def decision_system_prompt(*, reasoning: bool, answer: bool) -> str:
    fields = (_REASONING + "\n" if reasoning else "") + _FIELDS
    if answer:
        return (
            _SYSTEM_PROMPT + _MERGED_INTRO + "\n" + fields + _ANSWER_FIELD + _DATA_RULE
        )
    return _DECISION_INTRO + "\n" + fields + _DATA_RULE


def decision_schema(*, reasoning: bool, answer: bool) -> dict[str, Any]:
    """JSON-схема решения из модели Decision: без лишних полей, все
    поля обязательны (так требует строгий режим), порядок — как в модели."""
    schema = Decision.model_json_schema()
    properties = {
        name: {
            key: value for key, value in spec.items() if key not in ("title", "default")
        }
        for name, spec in schema["properties"].items()
        if (name != "reasoning" or reasoning) and (name != "answer" or answer)
    }
    return {
        "type": "object",
        "properties": properties,
        "required": list(properties),
        "additionalProperties": False,
    }


def decision_response_format(*, reasoning: bool, answer: bool) -> dict[str, Any]:
    return {
        "type": "json_schema",
        "json_schema": {
            "name": "decision",
            "schema": decision_schema(reasoning=reasoning, answer=answer),
            "strict": True,
        },
    }


def build_decision_messages(
    question: str,
    matches: Sequence[SourceChunk],
    *,
    reasoning: bool = False,
    answer: bool = False,
    searched: Sequence[tuple[str, int]] = (),
) -> list[Message]:
    """searched — уже сделанные доборы: (запрос, сколько новых выдержек).
    Без этого шаг решения не знает, что уже искали, и повторяет запрос."""
    excerpts = format_excerpts(matches) if matches else "(выдержек нет)"
    history = (
        "\n\nУже искали: "
        + "; ".join(f"«{query}» — новых выдержек: {added}" for query, added in searched)
        + ". Эти запросы не повторяй."
        if searched
        else ""
    )
    return [
        Message(
            role=Role.SYSTEM,
            content=decision_system_prompt(reasoning=reasoning, answer=answer),
        ),
        Message(
            role=Role.USER,
            content=(
                "Выдержки из документов компании:\n\n"
                f"{excerpts}\n\n"
                f"Сообщение сотрудника: {question.strip()}{history}"
            ),
        ),
    ]


def build_answer_messages(
    question: str, matches: Sequence[SourceChunk], decision: Decision | None
) -> list[Message]:
    """Ответ по выдержкам отдельным вызовом: промпт faq-v2.7 (без правила
    поиска — искать решает шаг решения). При другом годе или редакции —
    своя постановка задачи (edition-v1): правило 4 faq-v2.7 велит отказать."""
    if decision is not None and decision.match == "other_edition":
        return build_edition_messages(question, matches, decision)
    return build_faq_messages(question, matches)


def with_edition_note(answer: str, decision: Decision | None) -> str:
    """Ответ по другому году или редакции — первой фразой оговорка.

    edition-v1 велит модели написать её самой (год или редакцию она видит в
    выдержках, решение их не всегда называет); не написала — оговорка из
    решения (mismatch_note), если её есть из чего построить.
    """
    if decision is None or decision.match != "other_edition":
        return answer
    if answer.lstrip(" «*").startswith(NOTE_PREFIX):
        return answer
    note = mismatch_note(decision)
    return f"{note} {answer}" if note else answer


def with_other_subject_note(answer: str, decision: Decision | None) -> str:
    """«В документах компании ответа нет.» + «В документах — «X», а не «Y».»
    — сразу после пометки (решение Артёма 20.10: показывать, про что
    документы есть). Ответ без пометки в начале не трогаем."""
    if decision is None or decision.match != "other":
        return answer
    note = mismatch_note(decision)
    if not note or not answer.startswith(NOT_FOUND_ANSWER):
        return answer
    rest = answer[len(NOT_FOUND_ANSWER) :].lstrip()
    return f"{NOT_FOUND_ANSWER} {note}" + (f" {rest}" if rest else "")
