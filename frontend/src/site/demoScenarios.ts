/** Текст с маркерами [n] → куски текста и номера источников. */
export function splitMarkers(text: string): (string | number)[] {
  return text
    .split(/(\[\d\])/)
    .filter(Boolean)
    .map((part) => {
      const match = /^\[(\d)\]$/.exec(part);
      return match ? Number(match[1]) : part;
    });
}

/** «==фрагмент==» → куски: обычный текст и подсвеченный. */
export function splitHighlights(text: string): { text: string; mark: boolean }[] {
  return text
    .split(/(==[^=]+==)/)
    .filter(Boolean)
    .map((part) =>
      part.startsWith("==") && part.endsWith("==")
        ? { text: part.slice(2, -2), mark: true }
        : { text: part, mark: false },
    );
}
