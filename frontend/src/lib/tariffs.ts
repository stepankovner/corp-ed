export function tariffByCode(code: string | null): TariffInfo | undefined {
  return TARIFFS.find((tariff) => tariff.code === code);
}

/** «1 490 ₽» — разряды неразрывным пробелом, чтобы цена не переносилась. */
export function formatPrice(price: number): string {
  return `${String(price).replace(/\B(?=(\d{3})+(?!\d))/g, "\u00a0")}\u00a0₽`;
}

export function priceLabel(tariff: TariffInfo): string {
  return tariff.price === null ? "по запросу" : `${formatPrice(tariff.price)} за место в месяц`;
}
